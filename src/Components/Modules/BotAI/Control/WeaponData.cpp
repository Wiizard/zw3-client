	static bool GunTokenMatches(const char* name, const char* gun)
	{
		int i = 0;
		for (; gun[i]; ++i)
		{
			if (name[i] != gun[i])
			{
				return false;
			}
		}
		return name[i] == '_' || name[i] == '\0';
	}


	bool TryGetGunStats(const char* weaponName, GunStats* out)
	{
		if (!weaponName)
		{
			return false;
		}

		const GunStats* gun = nullptr;
		if (HasSubstring(weaponName, "_shotgun_attach"))
		{
			gun = &shotgunAttachStats[0];
		}
		for (const GunStats& candidate : gunStats)
		{
			if (gun)
			{
				break;
			}
			if (GunTokenMatches(weaponName, candidate.gun))
			{
				gun = &candidate;
			}
		}
		if (!gun)
		{
			return false;
		}

		*out = *gun;
		if (HasSubstring(weaponName, "_xmags") && gun->xmagsClipSize > 0)
		{
			out->clipSize = gun->xmagsClipSize;
		}
		if (HasSubstring(weaponName, "_rof") && gun->rofFireTimeMs > 0)
		{
			out->fireTimeMs = gun->rofFireTimeMs;
		}
		if (HasSubstring(weaponName, "_akimbo"))
		{
			out->hip = gun->akimboHip;
		}
		if (HasSubstring(weaponName, "_silencer") && gun->silencedMaxDamageRange > 0.0f)
		{
			out->maxDamageRange = gun->silencedMaxDamageRange;
			out->minDamageRange = gun->silencedMinDamageRange;
		}

		const bool hasAcog = HasSubstring(weaponName, "_acog");
		const bool hasThermal = HasSubstring(weaponName, "_thermal");
		if ((hasAcog || hasThermal) && gun->scopeAdsInTimeMs > 0)
		{
			out->adsInTimeMs = gun->scopeAdsInTimeMs;
			out->adsOutTimeMs = gun->scopeAdsOutTimeMs;
		}

		float centerDelta = 0.0f;
		if (hasAcog)
		{
			centerDelta += gun->acogCenterDelta;
		}
		if (hasThermal)
		{
			centerDelta += gun->thermalCenterDelta;
		}
		if (HasSubstring(weaponName, "_grip"))
		{
			centerDelta += gun->gripCenterDelta;
		}
		out->adsKick.centerSpeed += centerDelta;
		out->hipKick.centerSpeed += centerDelta;
		return true;
	}


	bool TryGetViewKick(const char* weaponName, bool isAds, ViewKick* out)
	{
		GunStats stats = {};
		if (!TryGetGunStats(weaponName, &stats))
		{
			return false;
		}
		if (isAds)
		{
			*out = stats.adsKick;
		}
		else
		{
			*out = stats.hipKick;
		}
		return true;
	}
